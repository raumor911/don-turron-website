/* DON TURRÓN / ATELIER MOTION · progressive enhancement, dependency-free */
(() => {
  'use strict';
  const root = document.documentElement;
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)');
  const fine = window.matchMedia('(hover: hover) and (pointer: fine)');
  const MOTION_KEY = 'dt-prefer-still-v1';
  try { if (localStorage.getItem(MOTION_KEY) === 'yes') root.classList.add('dt-still'); } catch (_) {}
  const active = () => !reduced.matches && !root.classList.contains('dt-still');
  const $ = selector => document.querySelector(selector);
  const $$ = selector => [...document.querySelectorAll(selector)];

  // The reading progress hairline is composited and never blocks controls.
  const progress = document.createElement('div');
  progress.className = 'dt-progress';
  progress.setAttribute('aria-hidden','true');
  document.body.appendChild(progress);
  let frame = 0;
  const paintProgress = () => {
    frame = 0;
    if (!active()) return;
    const max = document.documentElement.scrollHeight - innerHeight;
    const ratio = max > 0 ? Math.max(0, Math.min(1, window.scrollY / max)) : 0;
    progress.style.transform = `scaleX(${ratio})`;
  };
  const scheduleProgress = () => {
    if (!frame) frame = requestAnimationFrame(paintProgress);
  };
  window.addEventListener('scroll', scheduleProgress, {passive:true});
  window.addEventListener('resize', scheduleProgress, {passive:true});
  scheduleProgress();

  // Prepare elements before registering the observer, with a non-observer fallback.
  const targets = [
    ...$$('.section-header, .center-heading, .faq-layout > div:first-child, .quote-band-inner, .philosophy-text, .philosophy-frame, .closing-inner'),
    ...$$('.category-tile, .step')
  ];
  const show = element => element.classList.add('dt-inview');
  if ('IntersectionObserver' in window && active()) {
    targets.forEach((element,index) => {
      element.classList.add('dt-reveal');
      if (element.matches('.category-tile, .step')) {
        element.style.setProperty('--dt-delay', `${Math.min(index % 5,4) * 75}ms`);
      }
    });
    const observer = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        show(entry.target);
        observer.unobserve(entry.target);
      });
    }, {rootMargin:'0px 0px -35px 0px',threshold:0.06});
    targets.forEach(element => observer.observe(element));
    // A failed intersection event must never leave the content invisible.
    window.setTimeout(() => targets.forEach(show), 3500);
  }
  root.classList.add('dt-ready');

  // Pointer light follows within its own surface: no body-wide reflows or faux parallax.
  function trackLight(surface) {
    if (!surface) return;
    let raf = 0;
    let eventX = 0, eventY = 0;
    surface.addEventListener('pointermove', event => {
      if (!active() || !fine.matches || event.pointerType === 'touch') return;
      eventX = event.clientX; eventY = event.clientY;
      if (raf) return;
      raf = requestAnimationFrame(() => {
        raf = 0;
        const rect = surface.getBoundingClientRect();
        const x = Math.max(0,Math.min(100,(eventX-rect.left)/Math.max(1,rect.width)*100));
        const y = Math.max(0,Math.min(100,(eventY-rect.top)/Math.max(1,rect.height)*100));
        surface.style.setProperty('--dt-x',`${x.toFixed(1)}%`);
        surface.style.setProperty('--dt-y',`${y.toFixed(1)}%`);
      });
    }, {passive:true});
    surface.addEventListener('pointerleave', () => {
      if (raf) cancelAnimationFrame(raf);
      raf = 0;
      surface.style.removeProperty('--dt-x');
      surface.style.removeProperty('--dt-y');
    });
  }
  trackLight($('.hero'));
  $$('.category-tile').forEach(trackLight);
  // Product cards are dynamically regenerated by catalog filters.
  const grid = $('#product-grid');
  let productObserver;
  function decorateProducts() {
    if (!grid) return;
    $$('.product-card').forEach((card,index) => {
      if (card.dataset.dtEnhanced === 'true') return;
      card.dataset.dtEnhanced = 'true';
      trackLight(card.querySelector('.product-art'));
      if (active()) {
        card.style.setProperty('--dt-stagger',`${Math.min(index,5)*65}ms`);
        card.classList.add('dt-enter');
      }
    });
  }
  if (grid) {
    decorateProducts();
    productObserver = new MutationObserver(decorateProducts);
    productObserver.observe(grid,{childList:true});
  }

  // Selection acknowledgement is subtle and keeps the existing live toast.
  const count = $('#cart-count');
  if (count) {
    let last = count.textContent;
    const countObserver = new MutationObserver(() => {
      const current = count.textContent;
      if (current === last) return;
      last = current;
      if (!active()) return;
      count.classList.remove('dt-pulse');
      void count.offsetWidth;
      count.classList.add('dt-pulse');
    });
    countObserver.observe(count,{childList:true,characterData:true,subtree:true});
    count.addEventListener('animationend',()=>count.classList.remove('dt-pulse'));
  }

  // Choice: respect both OS reduced-motion and the visitor's own control.
  const footer = $('.footer-bottom');
  if (footer) {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'dt-motion-toggle';
    const sync = () => {
      const still = reduced.matches || root.classList.contains('dt-still');
      button.textContent = still ? 'Movimiento reducido' : 'Reducir movimiento';
      button.setAttribute('aria-pressed', String(still));
      button.setAttribute('aria-label',still ? 'Activar animaciones (si el sistema lo permite)' : 'Reducir las animaciones del sitio');
      if (still) targets.forEach(show);
      scheduleProgress();
    };
    button.addEventListener('click', () => {
      const nowStill = !root.classList.contains('dt-still');
      root.classList.toggle('dt-still',nowStill);
      try { localStorage.setItem(MOTION_KEY,nowStill ? 'yes' : 'no'); } catch (_) {}
      sync();
    });
    footer.appendChild(button);
    if (reduced.addEventListener) reduced.addEventListener('change',sync);
    else if (reduced.addListener) reduced.addListener(sync);
    sync();
  }
})();
